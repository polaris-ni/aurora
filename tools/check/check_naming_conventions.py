#!/usr/bin/env python3
# ============================================================================
# check_naming_conventions.py - public-API naming-consistency gate (SPEC.API.NAMING-CONSISTENCY.001)
# ----------------------------------------------------------------------------
# Spec: codespec/CODING_STANDARDS.md §11.2 (requirement SPEC.API.NAMING-CONSISTENCY.001 "极致命名一致性")
#   - 公共控件 / 枚举类型：PascalCase（Button、TextInput、Alignment…）
#   - 属性键：snake_case（on_click、font_size…），杜绝同义异名
#   - 事件名：snake_case 且 on_ 前缀（on_click、on_change…）
#   - 自由函数（debug 门面）：snake_case
#   - 枚举值：PascalCase（TopLeft、Center…）；colors 命名空间的 AURORA_*
#     常量（constexpr Color，见 core/color.h）按「常量前缀」惯例全大写，豁免
#
# Data source: aurora_api.json (the frozen API SSOT, regenerated by
# gen_api_tools; drift vs. real code is guarded separately by
# check_api_schema_sync, so the JSON side of this script only validates the
# JSON itself) -- plus, since the single-declaration property face landed, one
# source-side leg: the property mechanism's public-face whitelist (W1/W2 below),
# which reads include/aurora/** through the shared props_scan parser.
#
# Exit code: 1 on any naming violation; otherwise 0.
#
# Usage:
#   python3 tools/check/check_naming_conventions.py [--root <aurora_root>]
# ============================================================================
import argparse
import json
import os
import re
import sys

import props_scan  # 属性面的解析件（与三枚属性门禁同用一份，理由见其 docstring）

PASCAL_RE = re.compile(r"[A-Z][A-Za-z0-9]*")
SNAKE_RE = re.compile(r"[a-z][a-z0-9_]*")
# colors 命名空间常量惯例：constexpr Color AURORA_WHITE = ...（core/color.h）
CONST_RE = re.compile(r"AURORA_[A-Z0-9_]+")


def repo_root_of(path):
    d = os.path.dirname(os.path.abspath(path))
    while d and d != os.path.dirname(d):
        if os.path.isfile(os.path.join(d, "CMakeLists.txt")):
            return d
        d = os.path.dirname(d)
    return d


def check_name(kind, owner, name, pattern, violations, allow=None):
    if not isinstance(name, str) or not name:
        violations.append(f"{kind} in {owner!r}: missing/non-string name ({name!r})")
        return
    if pattern.fullmatch(name):
        return
    if allow and any(p.fullmatch(name) for p in allow):
        return
    violations.append(f"{kind} in {owner!r}: {name!r} does not match {pattern.pattern}")


# ----------------------------------------------------------------------------
# 属性机制层的公共面白名单（源码侧判定，与上面的 aurora_api.json 侧判定同批跑）
# ----------------------------------------------------------------------------
# 单一声明口径把「读一行」的全部通路收进两样东西：逐属性的具名件（`x()` / `x(ctx)` /
# `set_x(...)`，由表行推导）与两枚无逐属性替代的通用件（`clear(row)` 撤表态、`rows()` 表本体）。
# 机制层的其余通用件（`assign` / `rebind` / `resolve` / `stated` / `get` / `read` / `present` /
# `bind` / `props_descriptor` / `props_serialize` / `props_deserialize` / `collect_prop_sources`）
# 一旦升到公共面，读面就从「具名件 + 可推导」退化成「通用件 + 行选择器」—— 每属性都得先查
# 声明才知道怎么读，那正是被否决过的形态。故这里判两件事：
#   W1 属性继承链上的类，其 public 区不得声明/定义上述机制名；
#   W2 不得用 `using <基类>::<机制名>;` 把 protected 的机制件再暴露成 public（这是编译器侧
#      唯一的绕过通道，只判「有没有那枚声明」拦不住它）。
# 判定面限定在链上（类名是 `AbstractProps`、或基类清单里出现 `AbstractProps` / 以 `Props`
# 结尾的类型），链外同名接口不归它管：`State::get` / `Surface::present` / `Listener::bind` /
# `Url::resolve` 一类实测 48 处与属性面无关，按「include/ 全域」判等于把既有公共 API 一起判红。
MECHANISM_NAMES = frozenset({
    "assign", "rebind", "resolve", "stated", "get", "read", "present", "bind",
    "props_descriptor", "props_serialize", "props_deserialize", "collect_prop_sources",
})
# 类声明匹配：`class/struct Name [: 基类清单] {`。基类清单不许跨 `{`（排除同类体内的嵌套定义错位），
# 冒号段整体可选 —— `AbstractProps` 本体没有基类清单，而它正是这张白名单要守的那张面。
CHAIN_CLASS_RE = re.compile(r"^[ \t]*(?:class|struct)[ \t]+(\w+)[ \t]*((?::[^{;]+?)?)\{", re.M)
# 枚举行内的 `using 基类::名字;`（基类名可带模板实参，`using AbstractProps<ButtonProps>::bind;`
# 是把它拉回公共面的真实写法；继承构造的 `using 基类::基类;` 不在机制名集合里，自然放行）。
USING_RE = re.compile(r"^[ \t]*using[ \t]+([\w:]+(?:<[^;]*>)?)::(\w+)[ \t]*;", re.M)


def is_chain_class(name, clause):
    """类是否落在属性继承链上（判定面的成员资格判据）。

    未迁移的 `XxxProps` 是「公有字段聚合体」、声明里没有基类清单，故光看基类会把它们整批漏出
    判定面 —— 而白名单要守的正是「机制件不许出现在属性类的公共面上」，形态新旧都得判。
    """
    if name == "AbstractProps" or name.endswith("Props"):
        return True
    return "AbstractProps" in clause or bool(re.search(r"\b\w*Props\b", clause))


def chain_classes(text):
    """属性继承链上的类：返回 [(类名, 类体, 起始行偏移)]。"""
    found = []
    for m in CHAIN_CLASS_RE.finditer(text):
        if not is_chain_class(m.group(1), m.group(2)):
            continue
        body, _brace, line_offset = props_scan.class_body(text, m)
        if body is not None:
            found.append((m.group(1), body, line_offset))
    return found


def check_public_face(rel, text, findings):
    """对整篇头文件里的每枚链上类跑 W1 / W2；`text` 是去注释后的正文。"""
    for class_name, body, line_offset in chain_classes(text):
        spans = props_scan.parse_access_spans(body)
        for member in props_scan.parse_members(body, line_offset):
            if member.access == "public" and member.name in MECHANISM_NAMES:
                findings.append(f"{rel}:{member.line}: [W1] {class_name}::{member.name} is on the "
                                f"public face -- a property row is read and written through its named "
                                f"accessors; only `clear` and `rows` may reach the public face")
        for m in USING_RE.finditer(body):
            base, name = m.group(1), m.group(2)
            if name not in MECHANISM_NAMES or props_scan.access_for(spans, m.start()) != "public":
                continue
            findings.append(f"{rel}:{props_scan.line_of(body, m.start()) + line_offset}: [W2] "
                            f"{class_name} re-exposes protected {base}::{name} on the public face -- "
                            f"keep the mechanism member protected instead of lifting it back onto the face")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=None, help="Aurora repo root (default: two levels above this script)")
    args = ap.parse_args()
    root = args.root or repo_root_of(__file__)

    api_path = os.path.join(root, "aurora_api.json")
    if not os.path.isfile(api_path):
        print(f"[ERR] aurora_api.json not found: {api_path}", file=sys.stderr)
        return 2
    with open(api_path, encoding="utf-8") as f:
        api = json.load(f)

    violations = []

    # ---- Widget types: PascalCase ----
    prop_keys = set()
    event_names = set()
    widget_count = 0
    for w in api.get("widgets", []):
        owner = w.get("type", "<unknown widget>")
        widget_count += 1
        check_name("widget type", owner, w.get("type"), PASCAL_RE, violations)
        # 属性键取自单一权威表 props[].name
        for p in w.get("props") or []:
            if isinstance(p, dict) and p.get("name"):
                prop_keys.add(p["name"])
        # events 序列化为扁平字符串序列，每三项一组：(name, signature, description)，
        # 如 ["on_select", "void(int)", "点击某项时回调…"]；事件名统一为 on_ 前缀 snake_case。
        for ev in w.get("events") or []:
            candidates = ev if isinstance(ev, list) else [ev]
            for item in candidates:
                if isinstance(item, str) and item.startswith("on_"):
                    event_names.add(item)

    # ---- Property keys: snake_case ----
    for k in sorted(prop_keys):
        check_name("property key", "widget props", k, SNAKE_RE, violations)

    # ---- Event names: snake_case + on_ prefix ----
    for ev in sorted(event_names):
        check_name("event name", "widget events", ev, SNAKE_RE, violations)
        if isinstance(ev, str) and SNAKE_RE.fullmatch(ev) and not ev.startswith("on_"):
            violations.append(f"event name in widget events: {ev!r} must use on_ prefix")

    # ---- Enums: type PascalCase; values PascalCase (AURORA_* constants exempt) ----
    enum_count = 0
    for e in api.get("enums", []):
        owner = e.get("name", "<unknown enum>")
        enum_count += 1
        check_name("enum type", "enums", e.get("name"), PASCAL_RE, violations)
        for v in e.get("values") or []:
            check_name("enum value", owner, v, PASCAL_RE, violations, allow=[CONST_RE])

    # ---- Debug facade free functions: snake_case ----
    for fn in api.get("debug") or []:
        check_name("debug function", "aurora::debug", fn.get("name"), SNAKE_RE, violations)

    # ---- 属性机制层的公共面白名单（W1 / W2，源码侧） ----
    face = []
    chain_count = 0
    migrated_count = 0
    for path, rel in props_scan.header_files(root):
        text = props_scan.read_stripped(path)
        chain_count += len(chain_classes(text))
        migrated_count += len(props_scan.migrated_props_classes(text))
        check_public_face(rel, text, face)
    if chain_count == 0:
        face.append("[FAIL] no class on the property inheritance chain is in include/ -- the "
                    "public-face whitelist is spinning on an empty set (a Props class must exist "
                    "before this check can hold)")
    if migrated_count == 0:
        face.append("[FAIL] no Props class inherits AbstractProps -- the whitelist has nothing to "
                    "guard (a migrated widget must be registered before this check can hold)")

    if violations or face:
        if violations:
            print(f"[FAIL] {len(violations)} public-API naming violation(s) in aurora_api.json")
            print("       (spec: CODING_STANDARDS.md section 11.2 -- types PascalCase, props/events/functions snake_case,")
            print("        events on_-prefixed; AURORA_* color constants are the exempt constant convention):")
        for v in violations:
            print(f"  {v}")
        if face:
            print(f"[FAIL] {len(face)} property public-face whitelist violation(s) in include/ "
                  "(only `clear` and `rows` may come from the property mechanism; spec: the "
                  "single-declaration rule set in codespec/specification/04-widget.md)")
        for v in face:
            print(f"  {v}")
        return 1

    print(f"[PASS] naming conventions OK: {widget_count} widget types, {len(prop_keys)} property keys, "
          f"{len(event_names)} event names, {enum_count} enums, {len(api.get('debug') or [])} debug functions; "
          f"property public face carries no mechanism names ({chain_count} chain class(es) scanned, "
          f"{migrated_count} migrated Props, 0 finding(s) on W1/W2)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
