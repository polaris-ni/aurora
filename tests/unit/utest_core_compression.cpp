auto expected_payload() -> std::vector<char> { return {AURORA_TEST_PAYLOAD.begin(), AURORA_TEST_PAYLOAD.end()}; }

auto expected_large_payload() -> std::vector<char> {
    std::vector<char> out;
    out.reserve(AURORA_TEST_LARGE_LINE.size() * 5000U);
    for (int i = 0; i < 5000; ++i) {
        out.insert(out.end(), AURORA_TEST_LARGE_LINE.begin(), AURORA_TEST_LARGE_LINE.end());
    }
    return out;
}

/// 夹具按 uint8_t 保存（避免 >127 字节在 char 列表初始化中窄化），调用前转 span<const char>（助手名避开
/// std::as_bytes）。 同时接 std::array（夹具本体）与 std::vector（截断/翻字节等派生容器）。
template <typename Container>
auto fixture_span(const Container &v) -> std::span<const char> {
    // NOLINTNEXTLINE(*-pro-type-reinterpret-cast)
    const auto *chars = reinterpret_cast<const char *>(v.data());
    return {chars, v.size()};
}

