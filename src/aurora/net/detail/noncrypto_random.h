// noncrypto_random.h —— 库内置的非密码学伪随机序列（仅库实现可见，不属公共 API）。
//
// 为何单列：两处需要「不必安全、但必须散得开」的取值——重试退避的抖动（`http_retry`：打散同一时刻整批
// 重发的节奏）与链路标识的取值（`http_request_id`：`RFC 9562` UUIDv4 里那 122 位随机位）。各自写一份会
// 把同一套 LCG 参数复制两遍，而它对两个消费者只有一个共同要求：够散。落在这里，序列只有一处定义、
// 一份进程内状态。
//
// 三条口径（规范性，落码与文档回写以此为准）：
// - **刻意不用 `std::random_device`**：它在 MinGW 腿是确定性伪随机、在 wasm 腿可能直接抛，两个结果都会让
//   单测无法陈述「`jitter = 0` 时等待恰等于算得基准」这一类真值；而抖动不需要不可预测性，链路标识只需要
//   「本进程内不重复、跨进程不相关」。密码学质量的熵在这里没有消费者。
// - **进程内一次性播种、原子推进**：首次使用时以单调时钟的纪元计数播种（静态初始化本身线程安全），此后
//   CAS 推进，故多个 `Client` 在不同线程并发发起也各取到不同的值。
// - **只取高位**：LCG 的低数位周期短、相关性明显，故每一枚取值都取自序列状态的高位段。
#pragma once

#include <cstdint>

namespace aurora::net::detail {

/// @brief 推进一次序列并折算成 `[0, 1)` 的实数（退避抖动用）。
/// @return 落在 `[0, 1)` 的取值——上界取不到，故「基准 × (1 + jitter)」这一族的乘子恒在半开区间内。
[[nodiscard]] auto noncrypto_unit() -> double;

/// @brief 推进两次序列，各取一段 32 位有效位，拼成一枚 64 位定长取值（标识符构造用）。
/// @return 64 位整数；跨进程不相关，进程内逐次不同。
[[nodiscard]] auto noncrypto_u64() -> std::uint64_t;

}  // namespace aurora::net::detail
